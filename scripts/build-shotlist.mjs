// Builds docs/PHOTO_PROMPTS.md from docs/shot-list.json: one full prompt per shot, grouped by section.
// Also writes src/data/shot-meta.ts (placeholder tone and crop ratio per shot) for the site.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(root, "docs/shot-list.json"), "utf8"));

export function composePrompt(shot, d = data) {
  const mode = d.modes[shot.mode];
  const section = d.sections.find((s) => s.id === shot.section);
  const rim = (d.rims[shot.zone] ?? d.rims.Z4).phrase;
  const fill = (text) => text.replaceAll("{rim}", rim);
  return [
    shot.subject,
    section?.framing,
    fill(shot.light ?? mode.light),
    fill(mode.palette),
    d.style,
    d.negative[shot.people ?? "none"],
    `Aspect ratio ${shot.ratio}.`,
  ]
    .filter(Boolean)
    .join(" ");
}

export function lightLabel(shot, d = data) {
  return shot.mode === "rim" ? `rim light, ${d.rims[shot.zone].label} (${shot.zone})` : `${shot.mode} light`;
}

const shots = data.shots.map((s) => ({ ...s, prompt: composePrompt(s) }));
const order = { A: 0, B: 1, C: 2, D: 3 };

const md = [];
md.push("# Kadens — photo shot list", "");
md.push(`${shots.length} shots. Save every image with the exact file name below (any of jpg/png/webp) into \`${data.dropFolder}\`.`, "");
md.push(`Priorities: ${Object.entries(data.priorities).map(([k, v]) => `**${k}** ${v}`).join(" · ")}`, "");
md.push("## Workflow", "");
md.push("1. Use one model and the same settings for the whole series.");
md.push("2. Generate `hero` first, then `studio-cycle` (pulse light) and `zone-gym-floor` (steel light). Attach them as style references where the tool allows.");
md.push("3. Coaches are one series: generate `coach-boxing` first and attach it to every other coach prompt so the backdrop, distance and light match. Only the rim colour changes: it shows the coach's usual heart-rate zone.");
md.push("4. `hero-mobile` is a twin: make it by editing `hero` with the Edit prompt. Use the standalone prompt only if the tool cannot edit.");
md.push("5. Reject images with visible faces, text, numbers, logos or brand marks. Models like to put logos on equipment and weight numbers on plates.");
md.push("6. Highest available resolution, at least 2048 px on the long side. The exact ratio is cropped later by the photo script.", "");

for (const section of data.sections) {
  const list = shots.filter((s) => s.section === section.id).sort((a, b) => order[a.priority] - order[b.priority]);
  if (!list.length) continue;
  md.push(`## ${section.id}`, "");
  for (const s of list) {
    md.push(`### ${s.id}.jpg — ${s.ratio} · priority ${s.priority} · ${lightLabel(s)}`, "");
    if (s.edit) {
      md.push(`Edit prompt (attach \`${s.editFrom}\`):`, "", "```text", s.edit, "```", "");
      md.push("Standalone prompt:", "");
    }
    md.push("```text", s.prompt, "```", "");
  }
}
writeFileSync(join(root, "docs/PHOTO_PROMPTS.md"), md.join("\n"), "utf8");

const count = (p) => shots.filter((s) => s.priority === p).length;
console.log(`shots: ${shots.length} (${Object.keys(order).map((p) => `${p} ${count(p)}`).join(", ")})`);
console.log(`longest prompt: ${Math.max(...shots.map((s) => s.prompt.length))} chars`);

// Compact metadata for the site: placeholder tone and crop ratio per shot.
const meta = Object.fromEntries(shots.map((s) => [s.id, { mode: s.mode, ratio: s.ratio }]));
writeFileSync(
  join(root, "src/data/shot-meta.ts"),
  `// Generated by scripts/build-shotlist.mjs from docs/shot-list.json. Do not edit by hand.
export type ShotMode = ${Object.keys(data.modes).map((m) => JSON.stringify(m)).join(" | ")};
export const SHOT_META: Record<string, { mode: ShotMode; ratio: string }> = ${JSON.stringify(meta, null, 2)};
`,
  "utf8",
);
