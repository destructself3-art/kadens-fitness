/** What to suggest at the bottom of a space page. */
export function spaceCta(slug: SpaceSlug): { text: string; href: string; label: string } {
  switch (slug) {
    case "kids":
      return { text: "Часы, правила и заявка в детский клуб — на отдельной странице.", href: "/kids", label: "Детский клуб" };
    case "spa":
      return { text: "SPA входит не во все абонементы. В сравнении тарифов видно, где оно есть.", href: "/memberships", label: "Сравнить абонементы" };
    case "lobby":
      return { text: "С ресепшена начинается первый визит: бесплатное пробное занятие с тренером и пульс-тест.", href: "/trial", label: "Записаться на пробную" };
    default:
      return { text: "Первый визит бесплатный: пробное занятие с тренером и пульс-тест. Приходите посмотреть на зал своими глазами.", href: "/trial", label: "Записаться на пробную" };
  }
}

