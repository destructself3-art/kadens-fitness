type PlanSlug = Membership["slug"];

/** Biggest yearly saving across plans, in percent. */
export function maxYearlySaving(plans: Membership[]): number {
  return Math.max(0, ...plans.map((p) => (p.priceYearly ? Math.round((1 - p.priceYearly / p.price) * 100) : 0)));
}

